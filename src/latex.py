# src/latex.py
"""Booktabs LaTeX export of the formatted Markdown tables (no jinja2 needed). Used by src.seeds_tables."""
import re

import pandas as pd

SYMBOLS = [("|1 − R_H|", "$|1-R_H|$"), ("R_H", "$R_H$"), ("±", "$\\pm$"), ("†", "$^{\\dagger}$"), ("‡", "$^{\\ddagger}$"),
           ("↑", "$\\uparrow$"), ("↓", "$\\downarrow$"), ("→", "$\\to$"), ("−", "$-$"), ("λ", "$\\lambda$"), ("×", "$\\times$")]
ESCAPES = [("\\", "\\textbackslash{}"), ("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#")]


def cell(value) -> str:
    """Symbols become placeholders first, so the escaping does not touch the math they turn into."""
    text = re.sub(r"\*\*(.+?)\*\*", "\x01\\1\x02", str(value))
    text = re.sub(r"(?<=[\d\x02†‡])\*", "\x03", text)
    for index, (old, _) in enumerate(SYMBOLS):
        text = text.replace(old, f"\x00{index}\x00")
    for old, new in ESCAPES:
        text = text.replace(old, new)
    for index, (_, new) in enumerate(SYMBOLS):
        text = text.replace(f"\x00{index}\x00", new)
    return text.replace("\x01", "\\textbf{").replace("\x02", "}").replace("\x03", "$^{*}$").replace("$$", "${}$")


def booktabs(frame: pd.DataFrame, caption: str, label: str, align: str | None = None) -> str:
    align = align or "l" + "r" * (len(frame.columns) - 1)
    rows = [" & ".join(cell(v) for v in row) + " \\\\" for row in frame.astype(str).itertuples(index=False)]
    return "\n".join([
        "% Generated by python -m src.seeds_tables; needs \\usepackage{booktabs}.",
        "\\begin{table*}[t]", "\\centering", "\\small", f"\\caption{{{cell(caption)}}}", f"\\label{{{label}}}",
        f"\\begin{{tabular}}{{{align}}}", "\\toprule", " & ".join(cell(c) for c in frame.columns) + " \\\\", "\\midrule",
        *rows, "\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
